import type { DiscountType, ProductStatus } from '@sher/core-domain';

import type { TenantContext } from '../ports/tenant-context';
import type { Tx } from '../ports/unit-of-work';

/**
 * A product row exactly as stored (migration 0008) — plus the names of the rows
 * it points at, because a list of products with no brand or unit names is a list
 * nobody can read, and fetching them one by one would be a query per row.
 *
 * `purchasePriceMinor` is always read here. Whether it reaches the client is the
 * use case's decision (`inventory.cost.view`, UI-40) — a repository does not make
 * permission decisions (R-B6).
 */
export interface ProductRow {
  readonly id: string;
  readonly name: string;
  readonly brandId: string | null;
  readonly brandName: string | null;
  readonly categoryId: string | null;
  readonly categoryName: string | null;
  readonly parentCategoryName: string | null;
  readonly sku: string | null;
  readonly barcode: string | null;
  readonly description: string | null;
  readonly baseUnitId: string;
  readonly baseUnitName: string;
  readonly purchasePriceMinor: number;
  readonly sellingPriceMinor: number;
  readonly minStockQty: number;
  readonly status: ProductStatus;
  readonly defaultDiscountType: DiscountType | null;
  readonly defaultDiscountValue: number | null;
  readonly offerEnabled: boolean;
  readonly offerPriceMinor: number | null;
  readonly offerStartAt: Date | null;
  readonly offerEndAt: Date | null;
  readonly tracksExpiry: boolean;
  readonly tracksSerial: boolean;
  /**
   * The optional conversion (D-41). Both columns are set or both are null; the
   * unit's name is joined in, because a row showing an id is unreadable.
   */
  readonly conversionUnitId: string | null;
  readonly conversionUnitName: string | null;
  readonly conversionFactorQty: number | null;
  readonly version: number;
}

/** What a write supplies. Ids are generated by the use case (R-C1). */
export interface NewProduct {
  readonly id: string;
  readonly name: string;
  readonly baseUnitId: string;
  readonly purchasePriceMinor: number;
  readonly sellingPriceMinor: number;
  readonly minStockQty: number;
  readonly brandId: string | null;
  readonly categoryId: string | null;
  readonly sku: string | null;
  readonly barcode: string | null;
  readonly description: string | null;
  readonly defaultDiscountType: DiscountType | null;
  readonly defaultDiscountValue: number | null;
  readonly offerEnabled: boolean;
  readonly offerPriceMinor: number | null;
  readonly offerStartAt: Date | null;
  readonly offerEndAt: Date | null;
  readonly tracksExpiry: boolean;
  readonly tracksSerial: boolean;
  readonly conversionUnitId: string | null;
  readonly conversionFactorQty: number | null;
}

export type ProductEdit = Omit<NewProduct, 'id'>;

/**
 * List filters. `categoryId` matches the category itself **or** any subcategory
 * of it — choosing "Drinks" means everything filed under Drinks.
 */
export interface ProductFilter {
  readonly search: string | null;
  readonly brandId: string | null;
  readonly categoryId: string | null;
  readonly status: ProductStatus | null;
  /** Keyset cursor: the id of the last row of the previous page (§3.9). */
  readonly cursor: string | null;
  readonly limit: number;
}

/** Counts for the summary tiles, over the same filter as the rows. */
export interface ProductCounts {
  readonly total: number;
  readonly active: number;
  readonly inactive: number;
  readonly withoutBarcode: number;
}

/**
 * Products (migration 0008). Business-specific, per D-14 — shaped so a SQLite
 * implementation can satisfy it in Phase 12 without changing a use case.
 *
 * No business rule lives here (R-B6): duplicate codes, feature gating, cost
 * visibility and the optimistic lock are decided in `ManageProductsService`.
 */
export interface ProductRepository {
  /**
   * One page of products in a fixed order — name, then id as the tiebreak, which
   * is the order the screen shows and the order the cursor walks. `OFFSET` is
   * banned (§3.9); the cursor is the previous page's last id and the query looks
   * its sort key up.
   */
  list(tx: Tx, ctx: TenantContext, filter: ProductFilter): Promise<readonly ProductRow[]>;
  /** Counts over the same filter, minus paging, so a tile matches its table. */
  count(tx: Tx, ctx: TenantContext, filter: ProductFilter): Promise<ProductCounts>;

  findById(tx: Tx, ctx: TenantContext, id: string): Promise<ProductRow | null>;
  /** For the duplicate-code checks; returns the owning product's id, if any. */
  findIdByBarcode(tx: Tx, ctx: TenantContext, barcode: string): Promise<string | null>;
  findIdBySku(tx: Tx, ctx: TenantContext, sku: string): Promise<string | null>;

  insert(tx: Tx, ctx: TenantContext, product: NewProduct): Promise<void>;
  /**
   * Updates only when `expectedVersion` still matches (D-32). Returns false when
   * it does not, so the use case can raise `CONFLICT_STALE_VERSION` rather than
   * quietly overwriting the other person's edit.
   */
  update(
    tx: Tx,
    ctx: TenantContext,
    id: string,
    expectedVersion: number,
    product: ProductEdit,
  ): Promise<boolean>;
  setStatus(tx: Tx, ctx: TenantContext, id: string, status: ProductStatus): Promise<void>;
  setBarcode(tx: Tx, ctx: TenantContext, id: string, barcode: string): Promise<void>;
  /** Hard delete, only ever called for a product nothing refers to (§3.6). */
  deleteUnused(tx: Tx, ctx: TenantContext, id: string): Promise<void>;

  /** How many live products use a unit / brand / category (§3.6 delete-or-archive). */
  countUsingUnit(tx: Tx, ctx: TenantContext, unitId: string): Promise<number>;
  countUsingBrand(tx: Tx, ctx: TenantContext, brandId: string): Promise<number>;
  countUsingCategory(tx: Tx, ctx: TenantContext, categoryId: string): Promise<number>;
}
